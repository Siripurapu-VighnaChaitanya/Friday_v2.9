import os
import re
from fpdf import FPDF
from datetime import datetime


# ─── Language colour accent (RGB) ───────────────────────────────────────────
LANG_COLORS = {
    "python":     (79,  158, 227),   # Blue
    "javascript": (240, 219,  79),   # Yellow
    "js":         (240, 219,  79),
    "java":       (232,  86,   0),   # Orange
    "cpp":        (100, 160, 240),   # Steel blue
    "c":          (100, 160, 240),
    "html":       (228,  77,  38),   # HTML orange-red
    "php":        (119, 123, 179),   # Purple
}
DEFAULT_COLOR = (0, 200, 150)        # Teal fallback


def _accent(language: str):
    return LANG_COLORS.get(language.lower(), DEFAULT_COLOR)


def _clean_code(raw: str) -> str:
    """Strip markdown fences and return bare code."""
    if "```" in raw:
        match = re.search(r'```(?:\w+)?\s*\n?(.*?)\n?```', raw, re.DOTALL)
        if match:
            return match.group(1)
        return raw.replace("```", "")
    return raw


def _latin(text: str) -> str:
    """Encode to latin-1 (FPDF built-in fonts only support it)."""
    return text.encode("latin-1", "replace").decode("latin-1")


class CodePDF(FPDF):
    """Custom FPDF subclass with a polished header / footer."""

    def __init__(self, language: str, task: str):
        super().__init__()
        self.language = language
        self.task     = task
        self.accent   = _accent(language)

    # ── Header ────────────────────────────────────────────────────────────
    def header(self):
        r, g, b = self.accent

        # Dark top banner
        self.set_fill_color(15, 17, 26)
        self.rect(0, 0, 210, 28, "F")

        # Coloured left bar
        self.set_fill_color(r, g, b)
        self.rect(0, 0, 4, 28, "F")

        # Title
        self.set_xy(8, 6)
        self.set_font("helvetica", "B", 13)
        self.set_text_color(r, g, b)
        self.cell(80, 8, "F.R.I.D.A.Y  CODE", ln=False)

        # Language badge (right side)
        badge_x = 210 - 8 - 32
        self.set_fill_color(r, g, b)
        self.set_xy(badge_x, 7)
        self.set_font("helvetica", "B", 9)
        self.set_text_color(15, 17, 26)
        self.cell(32, 8, self.language.upper(), align="C", fill=True,
                  border=False, ln=False)

        # Subtitle – task description
        self.set_xy(8, 17)
        self.set_font("helvetica", "", 7)
        self.set_text_color(140, 150, 170)
        task_text = _latin(self.task[:110] + ("…" if len(self.task) > 110 else ""))
        self.cell(160, 5, task_text)

        self.ln(16)   # gap below header

    # ── Footer ────────────────────────────────────────────────────────────
    def footer(self):
        self.set_y(-12)
        # Thin separator line
        r, g, b = self.accent
        self.set_draw_color(r, g, b)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(1)
        self.set_font("helvetica", "I", 7)
        self.set_text_color(130, 130, 150)
        ts = datetime.now().strftime("%Y-%m-%d  %H:%M:%S")
        self.cell(0, 6,
                  f"Generated by Friday AI  ·  {ts}  ·  Page {self.page_no()}",
                  align="C")


def save_code_as_pdf(code_content: str, language: str = "python",
                     task: str = "") -> str:
    """
    Saves generated code as a beautifully formatted PDF on the Desktop.

    Args:
        code_content: Raw AI output (may contain markdown fences).
        language:     Programming language name.
        task:         The original user request (used for subtitle).

    Returns:
        A spoken confirmation string.
    """
    try:
        # ── 1. Extract pure code ─────────────────────────────────────────
        code = _clean_code(code_content).strip()
        lines = code.split("\n")

        # ── 2. Output path ───────────────────────────────────────────────
        desktop   = os.path.join(os.path.expanduser("~"), "Desktop")
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename  = f"FridayCode_{language}_{timestamp}.pdf"
        filepath  = os.path.join(desktop, filename)

        # ── 3. Build PDF ─────────────────────────────────────────────────
        pdf = CodePDF(language=language, task=task or f"{language} code")
        pdf.set_auto_page_break(auto=True, margin=18)
        pdf.add_page()

        r, g, b = _accent(language)

        # ── Dark code-block background ────────────────────────────────────
        # We'll draw it line-by-line so it auto-expands across pages.
        LINE_H     = 5.2    # mm per code line
        FONT_SIZE  = 8.5
        MARGIN_L   = 14     # left margin inside page
        CODE_W     = 182    # code area width
        NUM_COL_W  = 10     # line-number column width

        pdf.set_font("courier", size=FONT_SIZE)

        for idx, line in enumerate(lines, start=1):
            line_safe = _latin(line.rstrip())

            # Background fill for entire row (alternating subtle shade)
            if idx % 2 == 0:
                pdf.set_fill_color(18, 20, 30)
            else:
                pdf.set_fill_color(22, 24, 36)

            row_y = pdf.get_y()

            # Check if we need a page break before drawing
            if row_y + LINE_H > pdf.page_break_trigger:
                pdf.add_page()
                row_y = pdf.get_y()

            # Row background
            pdf.set_xy(MARGIN_L, row_y)
            pdf.cell(CODE_W, LINE_H, "", fill=True, border=False, ln=False)

            # Line number column
            pdf.set_xy(MARGIN_L, row_y)
            pdf.set_font("courier", "I", FONT_SIZE - 1.5)
            pdf.set_text_color(80, 90, 110)
            num_str = f"{idx:>3} "
            pdf.cell(NUM_COL_W, LINE_H, num_str, fill=False, border=False, ln=False)

            # Code text
            pdf.set_font("courier", "", FONT_SIZE)
            pdf.set_text_color(210, 220, 240)

            # Preserve leading spaces by replacing with non-breaking-space equivalent
            # (FPDF strips leading spaces, so we indent manually)
            leading_spaces = len(line_safe) - len(line_safe.lstrip(" "))
            indent_mm = leading_spaces * 1.82   # approx 1.82mm per space at size 8.5

            code_x = MARGIN_L + NUM_COL_W + indent_mm
            code_text = line_safe.lstrip(" ")

            # Wrap very long lines
            max_chars = int((CODE_W - NUM_COL_W - indent_mm) / 1.82)
            if max_chars < 10:
                max_chars = 10

            if len(code_text) <= max_chars:
                pdf.set_xy(code_x, row_y)
                pdf.cell(CODE_W - NUM_COL_W - indent_mm, LINE_H,
                         code_text, fill=False, border=False, ln=True)
            else:
                # First segment
                pdf.set_xy(code_x, row_y)
                pdf.cell(CODE_W - NUM_COL_W - indent_mm, LINE_H,
                         code_text[:max_chars], fill=False, border=False, ln=True)
                remainder = code_text[max_chars:]
                # Continuation lines (indented slightly more)
                while remainder:
                    cont_y = pdf.get_y()
                    if cont_y + LINE_H > pdf.page_break_trigger:
                        pdf.add_page()
                        cont_y = pdf.get_y()
                    pdf.set_fill_color(18, 20, 30)
                    pdf.set_xy(MARGIN_L, cont_y)
                    pdf.cell(CODE_W, LINE_H, "", fill=True, border=False, ln=False)
                    # continuation arrow
                    pdf.set_xy(MARGIN_L, cont_y)
                    pdf.set_font("courier", "I", FONT_SIZE - 2)
                    pdf.set_text_color(60, 70, 90)
                    pdf.cell(NUM_COL_W, LINE_H, "  ↩ ", border=False, ln=False)
                    pdf.set_font("courier", "", FONT_SIZE)
                    pdf.set_text_color(180, 190, 220)
                    cont_x = MARGIN_L + NUM_COL_W + 4
                    pdf.set_xy(cont_x, cont_y)
                    seg = remainder[:max_chars]
                    pdf.cell(CODE_W - NUM_COL_W - 4, LINE_H,
                             seg, fill=False, border=False, ln=True)
                    remainder = remainder[max_chars:]

        # ── Closing accent line ───────────────────────────────────────────
        pdf.ln(2)
        pdf.set_draw_color(r, g, b)
        pdf.set_line_width(0.5)
        pdf.line(MARGIN_L, pdf.get_y(), MARGIN_L + CODE_W, pdf.get_y())
        pdf.set_line_width(0.2)

        pdf.output(filepath)
        return f"I have saved the {language} code to your desktop, sir."

    except Exception as e:
        import traceback
        traceback.print_exc()
        print(f"[CodeController] PDF save error: {e}")
        return f"Sorry, I could not save the code. Error: {e}"
